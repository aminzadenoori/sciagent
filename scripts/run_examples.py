"""Run the agent on the showcase questions and write docs/examples_output.md (needs ANTHROPIC_API_KEY)."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sciagent.agent import ResearchAgent  # noqa: E402
from sciagent.index import HybridIndex  # noqa: E402

QUESTIONS = [
    "Can TransE model symmetric relations?",                                                   # conflicting evidence
    "Is CapsE better than RotatE on FB15k-237?",                                               # protocol-driven conflict
    "In Figure 1 of the leakage report, which dataset has the lowest bars, and roughly what values do they show?",  # multimodal
    "Compute the inverse-relation test leakage of WN18RR and explain which relations cause it.",  # analysis tool
    "What MRR does SMART achieve on YAGO3-10?",                                               # unanswerable
    "Why did the ARC living survey find that the best AI systems outperform humans on ARC-AGI-2?",  # false premise
    "According to the Open Research Knowledge Graph, which model has the highest Accuracy on the Story Cloze Test benchmark?",  # NL->SPARQL
]


def main():
    agent = ResearchAgent(HybridIndex.load(ROOT / "data" / "index"), ROOT / "data")
    md = ["# Example agent runs\n", "Generated by `python scripts/run_examples.py`.\n"]
    for q in QUESTIONS:
        print(q)
        r = agent.run(q)
        md += [f"\n## {q}\n", f"**Status:** {r.evidence_status} · **confidence:** {r.confidence:.2f} · "
               f"**{len(r.steps)} tool calls** · {r.seconds}s · {r.usage['input_tokens']}/{r.usage['output_tokens']} tokens\n",
               "**Tool trace:** " + " → ".join(f"`{s.tool}({json.dumps(s.args)[:80]})`" for s in r.steps) + "\n",
               r.answer + "\n"]
        if r.conflicts:
            md.append("**Conflicts:**\n" + "\n".join(f"- {c}" for c in r.conflicts) + "\n")
        md.append(f"**Citations:** {', '.join(r.citations) or '-'}\n")
        if r.guardrail_events or r.error:
            md.append(f"**Guardrails:** {r.guardrail_events} {r.error or ''}\n")
    out = ROOT / "docs" / "examples_output.md"
    out.write_text("\n".join(md))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
