"""Run the benchmark-leakage analysis and write it up as a PDF (figure + table).

The PDF is added to the corpus like any paper, so the agent can cite our own
computed evidence next to the literature, and the multimodal path (figure
extraction, table extraction, vision inspection) is exercised on a document
whose ground truth we know exactly.
"""
from __future__ import annotations

import io
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pymupdf

from .analysis import inverse_rule_eval, leakage_stats
from .data import load

DATASETS = ["WN18", "WN18RR", "FB15k-237"]
REPORT_ID = "report:kg-leakage"


def run(kg_root: Path) -> dict:
    res = {}
    for d in DATASETS:
        split = load(d, kg_root)
        res[d] = {"leakage": leakage_stats(split), "rule_model": inverse_rule_eval(split)}
    return res


def _figure(res) -> bytes:
    fig, ax = plt.subplots(figsize=(5.2, 3.0), dpi=140)
    x = range(len(DATASETS))
    leak = [res[d]["leakage"]["test_recoverable_by_rule_pct"] for d in DATASETS]
    mrr = [100 * res[d]["rule_model"]["MRR"] for d in DATASETS]
    ax.bar([i - 0.2 for i in x], leak, 0.4, label="test triples recoverable by a rule (%)", color="#4C72B0")
    ax.bar([i + 0.2 for i in x], mrr, 0.4, label="inverse-rule model MRR (x100)", color="#DD8452")
    for i, (a, b) in enumerate(zip(leak, mrr)):
        ax.text(i - 0.2, a + 1, f"{a:.1f}", ha="center", fontsize=7)
        ax.text(i + 0.2, b + 1, f"{b:.1f}", ha="center", fontsize=7)
    ax.set_xticks(list(x), DATASETS)
    ax.set_ylim(0, 105)
    ax.legend(fontsize=7, loc="upper right")
    ax.set_title("Inverse-relation test leakage in link-prediction benchmarks", fontsize=9)
    fig.tight_layout()
    buf = io.BytesIO()
    fig.savefig(buf, format="png")
    plt.close(fig)
    return buf.getvalue()


def write_report(res: dict, corpus_dir: Path) -> Path:
    (corpus_dir / "pdfs").mkdir(parents=True, exist_ok=True)
    arch = pymupdf.Archive()
    arch.add(_figure(res), "fig1.png")
    rows = "".join(
        f"<tr><td>{d}</td><td>{res[d]['leakage']['n_train']}</td><td>{res[d]['leakage']['n_test']}</td>"
        f"<td>{res[d]['leakage']['test_recoverable_by_rule_pct']:.2f}</td><td>{res[d]['rule_model']['MRR']:.3f}</td>"
        f"<td>{res[d]['rule_model']['Hits@10']:.3f}</td></tr>" for d in DATASETS)
    wn, rr, fb = (res[d] for d in DATASETS)
    html = f"""
<h1>Inverse-relation test leakage in WN18, WN18RR and FB15k-237</h1>
<p>Technical report generated by the sciagent data-analysis tool from the public benchmark files.</p>
<h2>Abstract</h2>
<p>We measure how many test triples of three link-prediction benchmarks can be recovered from the training set by a
mined rule (inverse, symmetric or equivalent relation), and evaluate a rule-only model that uses no embeddings. On WN18,
{wn['leakage']['test_recoverable_by_rule_pct']:.1f} percent of test triples are recoverable and the rule model reaches a filtered
MRR of {wn['rule_model']['MRR']:.3f}. On WN18RR the rule model drops to MRR {rr['rule_model']['MRR']:.3f}, and on FB15k-237 to
{fb['rule_model']['MRR']:.4f}.</p>
<h2>1. Method</h2>
<p>Training triples are augmented with reciprocal triples (t, r^-1, h). A rule q' =&gt; q is mined when at least 90 percent of
the entity pairs linked by q' are also linked by q, with a support of at least 10 pairs. The rule model gives score 1 to
every tail predicted by a rule and 0 otherwise. Ranks are computed in the filtered setting with the random tie-breaking
protocol, using the exact expectation over random placements, for both head and tail prediction.</p>
<p class="caption">Table 1. Leakage statistics and rule-model performance (filtered, random tie-breaking).</p>
<table><tr><th>Dataset</th><th>Train triples</th><th>Test triples</th><th>Recoverable test (%)</th><th>Rule MRR</th><th>Rule Hits@10</th></tr>{rows}</table>
<h2>2. Results</h2>
<p>On WN18 the mined rules are inverse pairs such as hyponym and hypernym, member holonym and member meronym, and part of
and has part. WN18RR removes these inverse pairs; the remaining recoverable test triples come from symmetric relations
(derivationally related form, verb group, similar to). FB15k-237 has {fb['leakage']['test_recoverable_by_rule_pct']:.1f} percent
recoverable test triples because entity pairs linked in training were removed from its test set.</p>
<img src="fig1.png" width="360"/>
<p class="caption">Figure 1. Percentage of test triples recoverable by a mined rule (blue) and filtered MRR x100 of the
rule-only model (orange) for WN18, WN18RR and FB15k-237.</p>
<h2>3. Conclusion</h2>
<p>High scores on WN18 can be obtained without learning embeddings, so WN18 and FB15k results should not be used to compare
models. WN18RR still contains symmetric relations that a rule solves for about a third of queries.</p>
"""
    css = "* {font-family: sans-serif;} body {font-size: 10px; line-height: 1.35;} h1 {font-size: 14px;} h2 {font-size: 12px;}" \
          " table {border-collapse: collapse;} td, th {border: 1px solid black; padding: 3px; font-size: 9px;} .caption {font-size: 9px; font-style: italic;}"
    story = pymupdf.Story(html=html, user_css=css, archive=arch)
    pdf_path = corpus_dir / "pdfs" / "report_kg_leakage.pdf"
    writer = pymupdf.DocumentWriter(str(pdf_path))
    rect = pymupdf.paper_rect("letter")
    more = True
    while more:
        dev = writer.begin_page(rect)
        more, _ = story.place(rect + (50, 50, -50, -50))
        story.draw(dev)
        writer.end_page()
    writer.close()
    meta = {"id": REPORT_ID, "title": "Inverse-relation test leakage in WN18, WN18RR and FB15k-237", "authors": ["sciagent"],
            "year": 2026, "venue": "generated report", "pdf": "pdfs/report_kg_leakage.pdf", "source": "generated"}
    (corpus_dir / "generated.jsonl").write_text(json.dumps(meta) + "\n")
    (corpus_dir / "kg_leakage_results.json").write_text(json.dumps(res, indent=1))
    return pdf_path
